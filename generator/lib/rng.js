// Reproduzierbarer Zufall: gleicher Seed → gleiche Aufgaben (Tests lassen sich wiederholen).
function hashString(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

// mulberry32
function makeRng(seed) {
  let a = (typeof seed === 'string' ? hashString(seed) : seed) >>> 0;
  const next = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const rng = {
    next,
    int: (min, max) => min + Math.floor(next() * (max - min + 1)),
    pick: (arr) => arr[Math.floor(next() * arr.length)],
    shuffle: (arr) => {
      const a2 = arr.slice();
      for (let i = a2.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        [a2[i], a2[j]] = [a2[j], a2[i]];
      }
      return a2;
    },
    // n verschiedene Werte aus [min, max]
    distinct: (n, min, max) => {
      if (max - min + 1 < n) throw new Error(`distinct: Bereich ${min}–${max} zu klein für ${n} Werte`);
      const set = new Set();
      while (set.size < n) set.add(rng.int(min, max));
      return [...set];
    },
  };
  return rng;
}

module.exports = { makeRng, hashString };
